<?php

namespace App\Services\Moderation\Ai;

use App\Enums\TrackOrigin;
use App\Models\AiJob;
use App\Models\Release;
use App\Models\Track;
use App\Services\Releases\TrackOrigins;

/**
 * Whether a track uploaded straight to a release is recorded music
 * (approve) or agentic, made mostly by AI (reject).
 *
 * @property Track $subject
 */
class TrackOriginCase extends ReviewCase
{
    public function __construct(Track $track, protected TrackOrigins $origins)
    {
        parent::__construct($track);
    }

    public function label(): string
    {
        return 'uploaded track';
    }

    public function isPending(): bool
    {
        return ! $this->subject->project_track_id
            && ! $this->subject->origin
            && $this->subject->origin_by !== TrackOrigins::ADMIN;
    }

    public function guidelines(): string
    {
        return <<<'TEXT'
            A creator uploaded a finished track straight to a release, without making it in the platform's studio.
            Tracks recorded or produced by people earn more from streams than tracks generated by AI.
            You cannot hear the audio. Judge from the details: the title and lyrics, the release's credits, label and
            description, the creator's history, and whether the creator already makes AI music on the platform.
            Approve when it reads as music made by people. Reject when it was most likely generated by AI, for
            example AI tool names in the credits or description, prompt-like titles or lyrics, or a creator whose other
            tracks are mostly AI-generated.
            When rejecting, the note says briefly why the track was ranked as AI-generated.
            TEXT;
    }

    public function brief(): string
    {
        $track = $this->subject->loadMissing('lyric');
        $release = Release::query()
            ->withoutGlobalScopes()
            ->find($track->release_id);
        $owner = $release
            ?->user()
            ->withoutGlobalScopes()
            ->first();

        $ownTracks = $owner
            ? Track::query()
                ->withoutGlobalScopes()
                ->whereIn('release_id', Release::query()->withoutGlobalScopes()->where('user_id', $owner->id)->select('id'))
                ->whereKeyNot($track->id)
                ->whereNotNull('origin')
                ->toBase()
                ->selectRaw('origin, count(*) as total')
                ->groupBy('origin')
                ->pluck('total', 'origin')
            : collect();

        $history = collect(TrackOrigin::cases())
            ->map(fn(TrackOrigin $origin) => "{$origin->title()}: " . (int) ($ownTracks[$origin->value] ?? 0))
            ->join(', ');

        return implode("\n", [
            'TRACK',
            "Title: {$track->title}",
            'Length: ' . (int) $track->duration . 's',
            'Description: ' . $this->clip($track->description, 600),
            'Lyrics: ' . $this->clip($track->lyric?->text, 800),
            '',
            'RELEASE',
            'Title: ' . ($release?->title ?? 'unknown'),
            'Description: ' . $this->clip($release?->description, 600),
            'Record label: ' . ($release?->record_label ?: 'none'),
            'Publisher: ' . ($release?->publisher ?: 'none'),
            'Composer: ' . ($release?->composer ?: 'none'),
            '',
            'CREATOR',
            'Account: @' . ($owner?->username ?? 'unknown') . ', joined ' . ($owner?->created_at?->toDateString() ?? 'unknown'),
            'Their other ranked tracks: ' . $history,
            'AI music jobs they ran: ' . ($owner ? AiJob::query()->where('user_id', $owner->id)->where('kind', 'music')->count() : 0),
        ]);
    }

    public function approve(?string $note): void
    {
        $this->origins->judged($this->subject, TrackOrigin::RECORDED);
    }

    public function reject(string $note): void
    {
        $this->origins->judged($this->subject, TrackOrigin::AGENTIC);
    }
}
